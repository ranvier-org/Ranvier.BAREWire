# Vendors BAREWire's sources into src/Ranvier.BAREWire/Vendor/BAREWire from its repository, at a branch, tag or commit.
#
#   pwsh scripts/vendor-barewire.ps1                       vendor the tip of main
#   pwsh scripts/vendor-barewire.ps1 -Ref <commit>         vendor a branch, tag or commit
#   pwsh scripts/vendor-barewire.ps1 -Check                fail when the committed files differ from the recorded commit
#
# What it writes:
#   src/...            every file BAREWire.fsproj compiles, byte for byte, at its own relative path
#   src/Encoding/Substrate/Float.fs
#                      generated: Float.Fable.fs and Float.Dotnet.fs, each unmodified, under `#if FABLE_COMPILER` and
#                      `#else`. BAREWire selects the float shim by project file; a NuGet package ships one source list
#                      for .NET and Fable, so the choice moves into the file.
#   BAREWire.props     the Compile list, in BAREWire.fsproj's order, imported by Ranvier.BAREWire.fsproj
#   LICENSE, PATENTS.md, Commercial.md
#                      BAREWire's licence files, packed into the NuGet package under licenses/BAREWire/
#   VENDORED.md        the remote, the commit and the file list
#
# Needs git and network access to the remote. With -Check and no -Ref, the commit recorded in VENDORED.md is used.
param(
    [string]$Ref,
    [string]$Remote = 'https://forge.spkez.dev/FidelityFramework/BAREWire',
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$vendor = Join-Path $root 'src/Ranvier.BAREWire/Vendor/BAREWire'
$dotnetShim = 'Encoding/Substrate/Float.Dotnet.fs'
$fableShim = 'Encoding/Substrate/Float.Fable.fs'
$mergedShim = 'Encoding/Substrate/Float.fs'
$licenceFiles = @('LICENSE', 'PATENTS.md', 'Commercial.md')
$work = Join-Path ([IO.Path]::GetTempPath()) ('ranvier-barewire-' + [guid]::NewGuid().ToString('N'))

function Invoke-Git {
    & git @args
    if ($LASTEXITCODE -ne 0) { throw "git $($args -join ' ') failed with exit code $LASTEXITCODE" }
}

# The file's text as UTF-8, with CRLF read as LF.
function Read-Normalised([string]$path) {
    [IO.File]::ReadAllText($path, [Text.UTF8Encoding]::new($false)).Replace("`r`n", "`n")
}

function Write-Text([string]$path, [string]$text) {
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $path) | Out-Null
    [IO.File]::WriteAllText($path, $text, [Text.UTF8Encoding]::new($false))
}

if (-not $Ref) {
    $Ref = 'main'
    if ($Check) {
        $record = Join-Path $vendor 'VENDORED.md'
        if (-not (Test-Path -LiteralPath $record)) { throw "$record is missing: vendor the sources before checking them." }
        $pinned = Select-String -LiteralPath $record -Pattern '^- Commit: `([0-9a-f]{40})`$' | Select-Object -First 1
        if (-not $pinned) { throw "$record records no commit." }
        $Ref = $pinned.Matches[0].Groups[1].Value
    }
}

try {
    $checkout = Join-Path $work 'upstream'
    $output = Join-Path $work 'vendor'
    Invoke-Git -c core.autocrlf=false clone --quiet --no-checkout $Remote $checkout
    Invoke-Git -C $checkout -c core.autocrlf=false -c advice.detachedHead=false checkout --quiet $Ref
    $commit = (& git -C $checkout rev-parse HEAD).Trim()
    $committed = (& git -C $checkout show -s --format=%cI HEAD).Trim()
    $subject = (& git -C $checkout show -s --format=%s HEAD).Trim()

    $project = [xml](Get-Content -LiteralPath (Join-Path $checkout 'src/BAREWire.fsproj') -Raw)
    $files = @($project.Project.ItemGroup.Compile | Where-Object { $_ } | ForEach-Object { $_.Include.Replace('\', '/') })
    if ($files.Count -eq 0) { throw 'src/BAREWire.fsproj lists no Compile item: the project layout changed.' }
    if ($files -notcontains $dotnetShim) { throw "src/BAREWire.fsproj no longer compiles $dotnetShim`: update the float shim handling in this script." }
    if (-not (Test-Path -LiteralPath (Join-Path $checkout "src/$fableShim"))) { throw "src/$fableShim is missing upstream: update the float shim handling in this script." }

    $compiled = @()
    foreach ($file in $files) {
        if ($file -eq $dotnetShim) {
            $merged = @(
                "// Generated by scripts/vendor-barewire.ps1 from BAREWire's $fableShim and $dotnetShim,"
                '// each unmodified. BAREWire selects one by project file; this file selects it by compiler.'
                '#if FABLE_COMPILER'
                (Read-Normalised (Join-Path $checkout "src/$fableShim")).TrimEnd("`n")
                '#else'
                (Read-Normalised (Join-Path $checkout "src/$dotnetShim")).TrimEnd("`n")
                '#endif'
                ''
            ) -join "`n"
            Write-Text (Join-Path $output "src/$mergedShim") $merged
            $compiled += $mergedShim
        }
        else {
            $target = Join-Path $output "src/$file"
            New-Item -ItemType Directory -Force -Path (Split-Path -Parent $target) | Out-Null
            Copy-Item -LiteralPath (Join-Path $checkout "src/$file") -Destination $target
            $compiled += $file
        }
    }

    foreach ($file in $licenceFiles) {
        $source = Join-Path $checkout $file
        if (-not (Test-Path -LiteralPath $source)) { throw "$file is missing upstream: the package must ship BAREWire's licence files." }
        Copy-Item -LiteralPath $source -Destination (Join-Path $output $file)
    }

    $items = $compiled | ForEach-Object { "    <Compile Include=`"Vendor/BAREWire/src/$_`" />" }
    $props = @(
        '<Project>'
        '  <!-- Generated by scripts/vendor-barewire.ps1 from BAREWire.fsproj. Do not edit: run the script. -->'
        '  <ItemGroup>'
        $items
        '  </ItemGroup>'
        '</Project>'
        ''
    ) -join "`n"
    Write-Text (Join-Path $output 'BAREWire.props') $props

    $listing = $compiled | ForEach-Object {
        if ($_ -eq $mergedShim) { "- ``src/$_`` (generated from ``$fableShim`` and ``$dotnetShim``)" } else { "- ``src/$_``" }
    }
    $record = @(
        '# Vendored BAREWire'
        ''
        'Written by `scripts/vendor-barewire.ps1`. Do not edit these files: change them upstream and run the script.'
        ''
        "- Remote: $Remote"
        "- Commit: ``$commit``"
        "- Committed: $committed"
        "- Subject: $subject"
        ''
        'BAREWire is copyright SpeakEZ Technologies, Inc. and licensed under the Apache License 2.0, with a commercial'
        'licence available: see `LICENSE`, `PATENTS.md` and `Commercial.md` beside this file. Every file under `src/` is'
        'the upstream file byte for byte, except the one marked generated, which holds two upstream files unmodified.'
        ''
        '## Files'
        ''
        $listing
        ''
    ) -join "`n"
    Write-Text (Join-Path $output 'VENDORED.md') $record

    $expected = @(Get-ChildItem -LiteralPath $output -Recurse -File | ForEach-Object {
            [IO.Path]::GetRelativePath($output, $_.FullName).Replace('\', '/')
        } | Sort-Object)

    if ($Check) {
        $present = @()
        if (Test-Path -LiteralPath $vendor) {
            $present = @(Get-ChildItem -LiteralPath $vendor -Recurse -File | ForEach-Object {
                    [IO.Path]::GetRelativePath($vendor, $_.FullName).Replace('\', '/')
                } | Sort-Object)
        }
        $differences = 0
        foreach ($file in $present | Where-Object { $expected -notcontains $_ }) {
            Write-Host "not from BAREWire at $commit`: $file"
            $differences++
        }
        foreach ($file in $expected) {
            $committedFile = Join-Path $vendor $file
            if (-not (Test-Path -LiteralPath $committedFile)) {
                Write-Host "missing: $file"
                $differences++
            }
            elseif ((Read-Normalised $committedFile) -cne (Read-Normalised (Join-Path $output $file))) {
                Write-Host "differs from BAREWire at $commit`: $file"
                $differences++
            }
        }
        if ($differences -gt 0) { throw "$differences vendored file(s) differ from $Remote at $commit." }
        Write-Host "The $($expected.Count) vendored files match $Remote at $commit."
    }
    else {
        if (Test-Path -LiteralPath $vendor) { Remove-Item -LiteralPath $vendor -Recurse -Force }
        New-Item -ItemType Directory -Force -Path (Split-Path -Parent $vendor) | Out-Null
        Copy-Item -LiteralPath $output -Destination $vendor -Recurse
        Write-Host "Vendored $($compiled.Count) source files from $Remote at $commit ($committed)."
    }
}
finally {
    if (Test-Path -LiteralPath $work) { Remove-Item -LiteralPath $work -Recurse -Force }
}
